/*
 * Prints the Prisma models for the content tables described in server/content/table-specs.ts.
 * Paste the output into prisma/schema.prisma (between the "content tables" markers) after
 * changing a spec, then create a migration.
 *
 *   node scripts/gen-content-models.ts
 */
import { TABLE_SPECS, columnName, fieldName, type Col } from "../server/content/table-specs.ts";

const prismaType = (c: Col) => ({ s: "String", i: "Int", f: "Float", b: "Boolean", ss: "String[]" })[c.t];

function field(c: Col): string {
  const name = fieldName(c);
  let type = prismaType(c);
  const attrs: string[] = [];
  if (c.t === "ss") attrs.push("@default([])");
  else if (c.opt) type += "?";
  if (c.unique) attrs.push("@unique");
  const col = columnName(name);
  if (col !== name) attrs.push(`@map("${col}")`);
  return `  ${name.padEnd(22)} ${type.padEnd(9)} ${attrs.join(" ")}`.trimEnd();
}

const out: string[] = ["// ---- content tables (generated by scripts/gen-content-models.ts) ----"];
for (const s of TABLE_SPECS) {
  const lines = [
    `/// ${s.doc}`,
    `model ${s.model} {`,
    `  id                     String   @id @default(cuid())`,
    `  /// order on the site and in the dashboard`,
    `  sortOrder              Int      @map("sort_order")`,
    ...s.cols.map(field),
    ...(s.groups ?? []).map((g) => `  ${g.flag.padEnd(22)} Boolean  @default(false) @map("${columnName(g.flag)}")`),
    `  /// dashboard user who created it`,
    `  author                 String?`,
    `  updatedBy              String?  @map("updated_by")`,
    `  createdAt              DateTime @default(now()) @map("created_at")`,
    `  updatedAt              DateTime @updatedAt @map("updated_at")`,
    ...s.children.map((c) => `  ${c.rel.padEnd(22)} ${c.model}[]`),
    "",
    `  @@index([sortOrder])`,
    ...s.cols.filter((c) => c.index).map((c) => `  @@index([${fieldName(c)}])`),
    `  @@map("${s.table}")`,
    `}`,
  ];
  out.push("", ...lines);
  for (const c of s.children) {
    out.push(
      "",
      `/// ${c.doc}`,
      `model ${c.model} {`,
      `  id                     Int      @id @default(autoincrement())`,
      `  ownerId                String   @map("owner_id")`,
      `  sortOrder              Int      @map("sort_order")`,
      ...c.cols.map(field),
      `  owner                  ${s.model}  @relation(fields: [ownerId], references: [id], onDelete: Cascade)`,
      "",
      `  @@index([ownerId])`,
      `  @@map("${c.table}")`,
      `}`,
    );
  }
}
out.push("", "// ---- end of content tables ----");
console.log(out.join("\n"));
